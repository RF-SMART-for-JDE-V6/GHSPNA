        /// <summary>
        /// Builds a string of keys delimited by commas for the current row in the table.
        /// The keys consist of the following:  SDKCOO, SDDOCO, SDDCTO, and SDLNID.
        /// </summary>
        /// <returns>Returns s string of keys delimited by a comma to be used to lock the
        /// record.  If the keys cannot be accessed because the table does not contain a
        /// current row, then just commas are returned.</returns>
        protected virtual string BuildKey()
        {
            try
            {
                return (SDKCOO + "," + SDDOCO.ToString() + "," + SDDCTO + "," + SDLNID.ToString());
            } // end try
            catch
            {
                return (",,,");
            } // end catch
        } // end BuildKey

        protected virtual string BuildConsolidatedKey()
        {
            try
            {
                if (Columns.SDSHAN.FormatColumn(this["SDSHAN"]).ToString().Trim().Length > 0)
                    return ($"{SDSHAN},{SDITM},{SDUOM},{SDMCU}");
                else
                    return ($"{SDROUT},{SDITM},{SDUOM},{SDMCU}");
            } // end try
            catch
            {
                return ($",,,");
            } // end catch
        } // end BuildKey

